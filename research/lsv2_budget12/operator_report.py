"""Report B3L3 operator profiles with explicit observational limits."""

import csv
import json
import sys
from pathlib import Path


def main() -> None:
    """Write the B3L3-only interpretation and all-operator evidence tables."""
    root = Path(sys.argv[1]) / "outputs/lsv2_budget12_20261028/operator_profile_b3l3"
    rows = list(csv.DictReader((root / "aggregate.csv").open(encoding="utf-8-sig")))
    per = list(csv.DictReader((root / "per_run.csv").open(encoding="utf-8-sig")))
    scope = json.loads((root / "scope.json").read_text())
    q = {r["operator"]: r for r in rows if r["arm"] == "Q1_NET_G9_B3L3" and r["n"] == "0"}
    u = {r["operator"]: r for r in rows if r["arm"] == "UNIFORM_B3L3" and r["n"] == "0"}
    report = r"""# B3L3 算子分类：成本、空调用、负奖励与偶发大收益

Material Passport：academic-research-suite / experiment-agent / validate；2026-10-28；ANALYZED；B3L3 operator profile v1。

按用户最新要求，只看B3L3：Q1 NET、折扣0.9为主，折扣0与随机B3L3交叉核对。没有借用B1L1的A4行为来给B3L3定性，没有新增服务器实验，也没有修改算子/奖励/状态。

## 口径

每臂16实例、每例一个种子；先算每run比例/均值，再对16实例等权平均。分规模、前沿分段、累计LS时间四分段分别保存在aggregate.csv、segments.csv、phases.csv。空调用指没有完整提案，不代表没做计算；非空但零即时HV与空调用分开。

正即时改进指局部HV增量大于1e-12；正净奖励指q_reward大于0。奖励已扣时间机会成本：

$$
r=\frac{\Delta HV-\rho t}{h}.
$$

“大正奖励事件”定义为达到该run全部正净奖励的95%分位数，仅为事后描述，不是新算法参数。奖励单位是校准分数，不是目标改善百分比。p99列是逐run分位数的均值，不是合并分位数；正奖励/空调用条件均值排除没有相应事件的run。局部HV的frame会变化，不能跨步相加冒充终点HV贡献。

## 全部算子主表

全部数字为Q9 B3L3；耗时是每次动作（至多3候选）的平均计费时间。正HV与负净奖励可以同时发生。

| 算子 | 调用数 | 空调用% | 正HV% | 负净奖励% | 毫秒/调用 | 平均净奖励 | 随机B3L3正HV% |
|---|---:|---:|---:|---:|---:|---:|---:|
"""
    for op, r in q.items():
        report += f"| {op} | {r['calls']} | {float(r['empty']) * 100:.1f} | {float(r['positive_hv']) * 100:.1f} | {float(r['negative']) * 100:.1f} | {float(r['seconds_mean']) * 1000:.1f} | {float(r['reward_mean']):+.3f} | {float(u[op]['positive_hv']) * 100:.1f} |\n"
    report += """
## 七类行为

### 1. P3：便宜、经常无完整候选、选择比例持续上升

空调用87.2%，即时正HV12.7%，负净奖励94.6%；空调用平均约35毫秒。选择比例从前1/4累计LS时间的13.8%升到最后1/4的47.9%，全程33.9%，占动作计费时间21.7%。约95.1%的P3选择发生在其属于最大Q集合时；这不是探索/利用分支的实际标记，随机探索也可能选中最大Q动作。

随机B3L3下P3空调用73.1%、正HV26.8%；Q0 B3L3中空调用88.4%、全程选择40.9%、末段54.0%。问题不只出现在折扣0.9时，不能全归咎未来项。

源码冻结Decode，扫描Prefill合法时间和电费改善，找到实际改善移动才返回提案。“空”既可能没有合法移动空间，也可能扫描后没有省电移动，当前日志不能逐项拆分原因。非空时几乎都有正HV；主要问题是许多访问状态下没有提案机会。

判断：优先核查机会与低成本奖励偏好，不直接删除。P3仍有真实收益；随机与Q访问状态不同，空调用差异不是同状态因果效应。

### 2. A4：便宜、几乎不空，但即时改善少

空调用0.8%，正HV5.7%，负奖励97.1%，平均52.6毫秒，平均净奖励-0.187。它对等待操作做前插，能构造候选不代表候选改善当前前沿；随机B3L3正HV也只有6.7%。

重要区别：B3L3中A4选择比例从前段10.1%降到后段8.7%，没有证据说学习器越来越偏爱它。不能移用B1L1的过选结论。Archive命中14.4%，高于5.7%的局部正HV，说明低局部HV不等于没有档案活动；是否有长期价值仍未确认。

判断：属于低效条件/精简消融的候选，但没有删去它后的效果证据。

### 3. A7：较贵、即时改进频繁，但不少改进仍被扣成负奖励

空调用6.6%，正HV52.1%，正净奖励18.5%，负净奖励81.5%，平均139.5毫秒。约33.6%的全部调用有正HV却仍是负净奖励。随机B3L3正HV57.8%，同样显示它在访问状态上经常带来即时改善。

它做单操作active-union packing，需要构造和筛选。空调用条件均时约247毫秒，所以空不一定便宜。100/200规模正HV分别64.9%/83.9%，分层差异明显。选择比例由14.0%降到6.5%，平均净奖励却为+1.258。不能仅凭总体均值认定Q选错：Q按状态决策，后期机会也变化；但应核查奖励和状态是否不合适地压制有效动作。

判断：当前不适合优先删，是频繁即时改善来源；命中率不是最终因果贡献。

### 4. P2_FLOW / P2_MIXED：重构成本较高，较多偶发大正奖励

空调用都约0.5%。破坏重构通常能完成候选，FLOW正HV19.1%、正净奖励12.0%、平均89.3毫秒；MIXED分别12.7%、6.4%、114.3毫秒。FLOW平均净奖励+1.900，MIXED约+0.012，不能认为两者一样有效。

FLOW大正奖励率1.39%，86次分布于13/16实例；MIXED 0.66%，34次分布于10/16。P3为0.19%；A7也有大收益（0.83%，13/16实例），所以大收益不是P2独占。

FLOW选择比例12.9%→4.8%，MIXED 8.3%→4.3%。较大即时净收益已有证据，“现在没收益、未来必有收益”仍没有由这些日志证明。FLOW在flow_end/中段/bill_end的正净奖励率约14.2%/6.4%/4.0%，属于情境线索，尚非经验证的决策规则。

判断：FLOW优先保留；MIXED应检验是否提供互补机会，不能只因名字相近就判冗余。

### 5. A3：较贵、非空低命中，回报高度集中于少数调用

空调用0%，正HV6.3%，负净奖励96.4%，平均157.7毫秒，是总体主表中最贵的动作。随机B3L3正HV4.5%；Q9平均净奖励-0.165，Q0约-0.872。源码是带电价代理排序的跨区域任务重分配，结构候选需要解码评价。

它并非没有大收益：10次大正奖励出现在7/16实例。最强1%调用平均贡献约89%的正奖励总量（先在每run计算，再对有正奖励run平均），说明收益很集中，不代表可预测或值得无限探索。200规模正HV约15.3%，不能拿总体低命中断言所有规模都没用。

判断：比A7/P2_FLOW更值得核查适用条件或做精简对比，但仍保留跨区域结构变化的功能差异，不直接删除。

### 6. A8：机会受限、经常无提案、偶发回报，已有门控

空调用64.2%，正HV5.7%，负奖励96.4%，平均38.6毫秒；有空调用run的条件均时48.4毫秒。7/16实例中全部A8调用是负净奖励，另外9个仍有正奖励。大正奖励7次，分布于4实例，均值容易受少数事件影响。

源码做峰值相关单体/支持组修复，可能因修复失败、未严格降峰或重复提案而空。日志没有拆分每种原因。已有分段空率门控，因此这里是门控放行后的条件统计，不能当无条件动作价值。

全程只占调用2.4%、动作时间1.7%，远小于P3。之前去A8仅在B6L5比较，不能移用成B3L3删除有效的证据。

判断：可检查资格和冗余，但按可节约资源衡量，并非第一优先。

### 7. A1 / A2 / A5：基础局部调整，各有功能，效果居中

A1是区域内单操作机器调整，A2是区域内P/D路径调整，A5是任务级顺序调整。空调用0%、0%、0.6%，正HV14.2%、14.4%、9.3%，平均48.8、77.8、62.6毫秒。平均净奖励分别+0.273、约0、-0.162。

它们不像P3高空，也不像A7高命中。A5本轮较弱，但没有同状态候选重叠/互补测试，不能直接判定它与A4或其他算子重复。

## 哪些全负、哪些偶尔有大正奖励

没有算子在全部16个Q9 B3L3运行中从未得到正奖励；所有算子的奖励中位数却都是负的。常见结果扣分、均值被少数正事件拉高，可以同时成立。

| 算子 | 全负实例数/16 | 大正奖励事件数 | 有大正奖励实例数/16 | 大正奖励率% | 正奖励条件均值 | 平均净奖励 |
|---|---:|---:|---:|---:|---:|---:|
"""
    for op, r in q.items():
        rr = [x for x in per if x["arm"] == "Q1_NET_G9_B3L3" and x["operator"] == op]
        report += f"| {op} | {int(r['all_negative_runs'])} | {sum(int(x['tail_events']) for x in rr)} | {sum(int(x['tail_events']) > 0 for x in rr)} | {float(r['tail_rate']) * 100:.2f} | {float(r['positive_reward_mean']):.2f} | {float(r['reward_mean']):+.3f} |\n"
    report += """
## 算子是否太多

现有证据能确认十个动作的成本、机会和收益形态差异很大，同一粗状态与成本奖励下的选择可能不够匹配。不能据此确认“十个太多”或某两个完全冗余；还没有B3L3删减组合或同状态候选重叠实验。

优先排查P3的高空与偏好，再看A4/A3低效条件；A8有门控且资源占比较低。A7、P2_FLOW优先保留作重要参照；MIXED看互补；基础动作保持功能区分。这是诊断优先级，不是新动作池。本次不改状态、阈值、奖励，不开新实验。

零局部HV可能仍伴随Archive变化或未来价值；大即时奖励也不保证对最终前沿贡献最大。即时改进、净奖励、Archive/种群活动、后续收益分别讨论。

## 验真与边界

"""
    report += f"只读{scope['runs']}个B3L3运行、{scope['steps']}步；{scope['source_hash_checks']}个日志SHA匹配回收manifest；{scope['independent_prior_operator_rows_checked']}组调用/空调用/正HV计数与先前分析交叉一致。新增测试覆盖非空、正HV、负净奖励可以共存，及随机日志不虚构Q奖励。未重跑求解器。\n\n"
    report += """11项解释检查均覆盖：按规模/分段防总体掩盖分层差异；run是分析单位，步骤不当独立样本；开发实例重复使用的筛选偏差明确；没有按奖励筛掉run；动作条件统计有策略选择偏差；分母与罕见事件数量同时报告；筛选胜者不当稳定效应；48run全纳入；未增加事后显著性主张；相关不等因果；后期变难可能反过来改变选择。分类是解释性分组，不是聚类训练，不提供删去某动作的反事实效果。

Notion连接器当前不可用，无法本轮重读/补写相关页。依据是已回收结果、上轮封存报告与冻结实现；本轮结论和09分析脚本记录待补，不称Notion闭环完成。
"""
    assert not any(s in report for s in ("\\(", "\\)", "\\[", "\\]", "\x0c", "\x08"))
    (root / "REPORT.md").write_text(report, encoding="utf-8")
    print(json.dumps(dict(characters=len(report), operators=len(q), runs=scope["runs"])))


if __name__ == "__main__":
    main()
